"""Build every timeline from the voice lengths → timelines.json (mixer) + timelines.js (page).
Stories keep their own local clocks; the master list places them one after another."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
CAPS = json.load(open(os.path.join(HERE, 'script', 'captions.json')))
D = json.load(open(os.path.join(HERE, 'voice', 'dur.json')))
ARJ = json.load(open(os.path.join(HERE, '..', '..', 'shorts', 'arjuna-birds-eye', 'timeline.json')))

def story(key, scenes, gaps={}, start=.8, tail=1.6, dflt=.5):
    t = start; voice = []
    for i in range(len(CAPS[key])):
        d = D[f'{key}_{i:02d}']; voice.append([round(t, 3), round(t + d, 3)]); t += d + gaps.get(i, dflt)
    dur = round(voice[-1][1] + tail, 2)
    ct = []
    for i, (a, b) in enumerate(voice):
        nxt = voice[i + 1][0] if i + 1 < len(voice) else dur
        ct.append([round(a - .05, 3), round(min(nxt - .05, max(a + 1.8, b + .6)), 3)])
    names = list(scenes); sc = {}
    for j, n in enumerate(names):
        a = 0 if j == 0 else round(voice[scenes[n]][0] - .45, 3)
        b = dur if j == len(names) - 1 else round(voice[scenes[names[j + 1]]][0] - .45, 3)
        sc[n] = [a, b]
    return dict(dur=dur, voice=voice, ct=ct, scenes=sc, caps=CAPS[key])

TLS = {}
TLS['ekalavya'] = story('ekalavya', dict(e1=0, e2=3, e3=6, e4=7, e5=9, e6=12, e7=14), {2: .9, 5: .8, 6: 1.2, 8: .9, 11: .9, 13: .9})
TLS['sudama'] = story('sudama', dict(k1=0, k2=2, k3=3, k4=6, k5=9, k6=12, k7=14), {1: .9, 2: .7, 5: .9, 8: .8, 11: .9, 13: .9})
TLS['monkey'] = story('monkey', dict(m1=0, m2=3, m3=5, m4=7, m5=10, m6=12), {2: .9, 4: .9, 6: .9, 9: .7, 11: 1.0})
# Arjuna: its own timeline, ending before its curtain scene
a_end = ARJ['scenes']['s10'][0] + .3
TLS['arjuna'] = dict(dur=round(a_end, 2), voice=ARJ['voice'][:-1], ct=ARJ['ct'][:-1], scenes=ARJ['scenes'], release=ARJ['release'], impact=ARJ['impact'],
                     caps=json.load(open(os.path.join(HERE, '..', '..', 'shorts', 'arjuna-birds-eye', 'captions.json')))[:-1])
# Ganesha: the original caption times, English voice placed on them, ending before its curtain
TLS['ganesha'] = dict(dur=74.3, place=json.load(open(os.path.join(HERE, 'script', 'ganesha_place.json'))))

fv = lambda i: D[f'frame_{i:02d}']
segs = []
def seg(kind, dur, **k): segs.append(dict(kind=kind, dur=round(dur, 2), **k))
intro_v = [1.6, 1.6 + fv(0) + .5]
seg('intro', intro_v[1] + fv(1) + 1.8, voice=[[round(v, 3), round(v + fv(i), 3)] for i, v in enumerate(intro_v)], lines=[0, 1])
order = [('arjuna', 2, 'I', 'Arjuna and the Bird’s Eye'), ('ekalavya', 3, 'II', 'Ekalavya'), ('ganesha', 4, 'III', 'Ganesha’s Race Around the World'),
         ('sudama', 5, 'IV', 'Krishna and Sudama'), ('monkey', 6, 'V', 'The Monkey and the Crocodile')]
for key, li, num, title in order:
    seg('card', .7 + fv(li) + 1.9, voice=[[.7, round(.7 + fv(li), 3)]], lines=[li], num=num, title=title)
    seg('story', TLS[key]['dur'], id=key)
o = [1.0]; o.append(o[0] + fv(7) + .7); o.append(o[1] + fv(8) + 1.2)
seg('outro', o[2] + fv(9) + 2.6, voice=[[round(v, 3), round(v + fv(7 + i), 3)] for i, v in enumerate(o)], lines=[7, 8, 9])
t = 0
for s in segs: s['t0'] = round(t, 3); t += s['dur']
out = dict(total=round(t, 2), segs=segs, stories=TLS, frame=CAPS['frame'])
json.dump(out, open(os.path.join(HERE, 'timelines.json'), 'w'), indent=1, ensure_ascii=False)
open(os.path.join(HERE, 'timelines.js'), 'w').write('// generated by build_timelines.py\nwindow.LT = ' + json.dumps(out, ensure_ascii=False) + ';\n')
print('total %.1f s (%.1f min)' % (t, t / 60))
for s in segs: print(' %-6s %-9s %6.1f  %5.1f' % (s['kind'], s.get('id', s.get('num', '')), s['t0'], s['dur']))
