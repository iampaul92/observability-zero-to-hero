"""Timeline from the voice lengths → timeline.json (mixer) + timeline.js (page).
Scenes are runs of consecutive lines with the same scene key."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, 'script', 'script.json')))
D = json.load(open(os.path.join(HERE, 'voice', 'dur.json')))
t = 1.2; voice = []
for i, (ch, sc, txt) in enumerate(S):
    nxt = S[i + 1] if i + 1 < len(S) else None
    if sc == 'card': t += .5                      # breath before a chapter card
    d = D['v%03d' % i]; voice.append([round(t, 3), round(t + d, 3)]); t += d
    if nxt is None: break
    t += 1.3 if sc == 'card' else (.75 if nxt[1] != sc else .42)
DUR = round(voice[-1][1] + 6.0, 2)
ct = [[round(a - .05, 3), round(min((voice[i + 1][0] - .05) if i + 1 < len(voice) else DUR, max(a + 1.6, b + .5)), 3)] for i, (a, b) in enumerate(voice)]
scenes = []
for i, (ch, sc, txt) in enumerate(S):
    if not scenes or scenes[-1]['key'] != sc:
        a = 0 if not scenes else round(voice[i][0] - .4, 3)
        if scenes: scenes[-1]['b'] = a
        scenes.append(dict(key=sc, ch=ch, a=a, first=i))
    scenes[-1]['last'] = i
scenes[-1]['b'] = DUR
out = dict(dur=DUR, voice=voice, ct=ct, scenes=scenes, caps=[s[2] for s in S], chapters=[s[0] for s in S])
json.dump(out, open(os.path.join(HERE, 'timeline.json'), 'w'), indent=1, ensure_ascii=False)
open(os.path.join(HERE, 'timeline.js'), 'w').write('// generated by build_timeline.py\nwindow.TL = ' + json.dumps(out, ensure_ascii=False) + ';\n')
print('dur %.1f s = %d:%02d, %d scenes' % (DUR, DUR // 60, DUR % 60, len(scenes)))
