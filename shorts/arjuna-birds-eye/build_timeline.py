"""Builds the shared timeline from the voice lengths → timeline.json (for the mixer) and timeline.js (for the page)."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
caps = json.load(open(os.path.join(HERE, 'captions.json')))
dur = json.load(open(os.path.join(HERE, 'voice', 'dur.json')))
GAP = {1: .7, 4: .8, 6: .35, 7: .7, 8: .35, 9: .6, 10: .8, 11: .5, 12: .5, 13: .9, 14: 1.0, 15: .7, 16: 2.6, 17: .6, 18: 1.2, 19: .5, 20: .3, 21: 1.6}
t = .6; voice = []
for i, c in enumerate(caps):
    d = dur['c%02d' % i]; voice.append([round(t, 3), round(t + d, 3)]); t += d + GAP.get(i, .45)
CT = []
for i, (a, b) in enumerate(voice):
    nxt = voice[i + 1][0] if i + 1 < len(voice) else b + 3
    CT.append([round(a - .05, 3), round(min(nxt - .05, max(a + 1.8, b + .6)), 3)])
DUR = round(voice[-1][1] + 2.4, 2)
S = lambda i, k=.4: round(voice[i][0] - k, 3)
scenes = {'s1': [0, S(2)], 's2': [S(2), S(5)], 's3': [S(5), S(8)], 's4': [S(8), S(10)], 's5': [S(10), S(11)],
          's6': [S(11), round(voice[16][1] + .35, 3)], 's7': [round(voice[16][1] + .35, 3), S(17, .15)],
          's8': [S(17, .15), S(19)], 's9': [S(19), S(22, .9)], 's10': [S(22, .9), DUR]}
out = {'dur': DUR, 'voice': voice, 'ct': CT, 'scenes': scenes, 'release': round(voice[16][1] + .35, 3), 'impact': S(17, .15)}
json.dump(out, open(os.path.join(HERE, 'timeline.json'), 'w'), indent=1)
open(os.path.join(HERE, 'timeline.js'), 'w').write('// generated by build_timeline.py\nwindow.TL = ' + json.dumps(out) + ';\nwindow.CAPTEXT = ' + json.dumps(caps, ensure_ascii=False) + ';\n')
print('dur', DUR, 'scenes', scenes)
