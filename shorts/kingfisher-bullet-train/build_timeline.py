"""Timeline from the voice lengths → timeline.json (mixer) + timeline.js (page). Scenes start at caption numbers."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
caps = json.load(open(os.path.join(HERE, 'captions.json'))); dur = json.load(open(os.path.join(HERE, 'voice', 'dur.json')))
GAP = {0: .5, 2: .5, 3: .5, 4: .6, 6: .4, 7: .6, 9: .5, 11: .6, 13: .6, 14: .5, 15: .45, 16: .45, 17: .3, 18: .9, 19: .4}
SCENES = dict(train=0, tunnel=1, houses=4, engineer=5, bird=7, dive=8, beak=10, test=12, result=14, stats=16, finale=19)
t = .5; voice = []
for i in range(len(caps)):
    d = dur['c%02d' % i]; voice.append([round(t, 3), round(t + d, 3)]); t += d + GAP.get(i, .3)
DUR = round(voice[-1][1] + 2.2, 2)
ct = [[round(a - .03, 3), round(min((voice[i + 1][0] - .03) if i + 1 < len(voice) else DUR, max(a + 1.2, b + .25)), 3)] for i, (a, b) in enumerate(voice)]
names = list(SCENES); sc = {}
for j, n in enumerate(names):
    a = 0 if j == 0 else round(voice[SCENES[n]][0] - .2, 3)
    b = DUR if j == len(names) - 1 else round(voice[SCENES[names[j + 1]]][0] - .2, 3)
    sc[n] = [a, b]
out = dict(dur=DUR, voice=voice, ct=ct, scenes=sc, caps=caps)
json.dump(out, open(os.path.join(HERE, 'timeline.json'), 'w'), indent=1, ensure_ascii=False)
open(os.path.join(HERE, 'timeline.js'), 'w').write('// generated by build_timeline.py\nwindow.TL = ' + json.dumps(out, ensure_ascii=False) + ';\n')
print('dur', DUR); print(sc)
